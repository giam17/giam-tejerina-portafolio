import sharp from 'sharp'
import { readFile, writeFile, mkdir, stat } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const plan = JSON.parse(await readFile(path.join(root, 'scripts/assets.json'), 'utf8'))
const imports = []
const entries = []
const report = []
sharp.concurrency(2)
for (const [index, asset] of plan.images.entries()) {
  const source = path.join(root, asset.original)
  const metadata = await sharp(source).metadata()
  const baseWidth = Math.min(metadata.width, Math.ceil(asset.designWidth * 2))
  const widths = [...new Set([Math.ceil(asset.designWidth / 2), Math.ceil(asset.designWidth), baseWidth, metadata.width].map(w => Math.min(w, metadata.width)))].sort((a, b) => a - b)
  const candidates = []
  await mkdir(path.dirname(path.join(root, 'src/assets', asset.id)), { recursive: true })
  for (const width of widths) {
    const relative = `${asset.id}${width === baseWidth ? '' : `-${width}w`}.webp`
    const target = path.join(root, 'src/assets', relative)
    await sharp(source).resize({ width, withoutEnlargement: true, kernel: 'lanczos3' }).keepIccProfile().webp({ lossless: true, effort: 5 }).toFile(target)
    const name = `image${index}_${width}`
    imports.push(`import ${name} from './${relative}'`)
    candidates.push({ name, width, file: `src/assets/${relative}`, bytes: (await stat(target)).size })
  }
  // Full-resolution copies preserve every visible pixel and the complete alpha channel.
  const full = candidates.find(c => c.width === metadata.width)
  const originalPixels = await sharp(source).ensureAlpha().raw().toBuffer()
  const webpPixels = await sharp(path.join(root, full.file)).ensureAlpha().raw().toBuffer()
  if (originalPixels.length !== webpPixels.length) throw new Error(`Dimensions changed: ${asset.id}`)
  for (let i = 0; i < originalPixels.length; i += 4) {
    if (originalPixels[i + 3] !== webpPixels[i + 3] || (originalPixels[i + 3] > 0 && (originalPixels[i] !== webpPixels[i] || originalPixels[i + 1] !== webpPixels[i + 1] || originalPixels[i + 2] !== webpPixels[i + 2]))) throw new Error(`Lossless verification failed: ${asset.id}`)
  }
  const base = candidates.find(c => c.width === baseWidth)
  entries.push(`  [${base.name}, { designWidth: ${asset.designWidth}, candidates: [${candidates.map(c => `{ src: ${c.name}, width: ${c.width} }`).join(', ')}] }],`)
  const sourceBytes = (await stat(source)).size
  report.push({ id: asset.id, original: asset.original, originalWidth: metadata.width, originalHeight: metadata.height, originalBytes: sourceBytes, defaultBytes: base.bytes, defaultFile: base.file, losslessVerified: true, candidates })
  console.log(`${index + 1}/${plan.images.length} ${asset.id}: ${(sourceBytes / 1024).toFixed(0)} → ${(base.bytes / 1024).toFixed(0)} KB`)
}
await writeFile(path.join(root, 'src/assets/catalog.generated.ts'), `// Generated by npm run assets:optimize. Do not edit by hand.\n${imports.join('\n')}\n\nexport type ImageVariant = { src: string; width: number }\nexport type ImageAsset = { designWidth: number; candidates: ImageVariant[] }\nexport const imageCatalog = new Map<string, ImageAsset>([\n${entries.join('\n')}\n])\n`)
await mkdir(path.join(root, 'reports'), { recursive: true })
const totalOriginal = report.reduce((n, a) => n + a.originalBytes, 0)
const totalDefault = report.reduce((n, a) => n + a.defaultBytes, 0)
await writeFile(path.join(root, 'reports/assets.json'), JSON.stringify({ originalBytes: totalOriginal, defaultBytes: totalDefault, reductionPercent: (1 - totalDefault / totalOriginal) * 100, images: report }, null, 2) + '\n')
console.log(`Default image set: ${(totalOriginal / 1e6).toFixed(2)} → ${(totalDefault / 1e6).toFixed(2)} MB`)
